#!/usr/bin/env python3
"""
Add or remove course photos, then run this from the site folder:

    python3 update_photos.py

How photos work:
  * Each course has a folder:  photos/<course-id>/
    (open the course in the Ledger tab — it shows the exact folder name).
  * Drop pictures in that folder: .jpg, .jpeg, .png or .heic straight off your phone.
  * This script shrinks anything big to web size (1800px, ~0.5 MB), converts
    PNG/HEIC to JPG, then rewrites photos.js so the site shows them.
  * To remove a photo, delete the file and run the script again.

Work on COPIES of your photos — the script resizes files in the photos/ folder in place.
Uses macOS's built-in `sips`, so nothing needs installing (falls back to Pillow elsewhere).
"""
import json, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PHOTOS = os.path.join(ROOT, "photos")
MAX_PX = 1800
IMG_EXT = (".jpg", ".jpeg", ".png", ".heic", ".heif", ".webp")


def course_ids():
    try:
        txt = open(os.path.join(ROOT, "ledger-data.js"), encoding="utf-8").read()
    except OSError:
        return set()
    return set(re.findall(r'"id":\s*"([^"]+)"', txt))


def have_sips():
    return sys.platform == "darwin" and shutil.which("sips") is not None


def size_of(path):
    if have_sips():
        out = subprocess.run(["sips", "-g", "pixelWidth", "-g", "pixelHeight", path], capture_output=True, text=True).stdout
        nums = [int(n) for n in re.findall(r"pixel(?:Width|Height):\s*(\d+)", out)]
        return max(nums) if nums else 0
    from PIL import Image
    with Image.open(path) as im:
        return max(im.size)


def to_web_jpg(path):
    """Convert to JPG if needed and shrink to MAX_PX. Returns the final path."""
    base, ext = os.path.splitext(path)
    ext = ext.lower()
    target = base + ".jpg"
    needs_convert = ext not in (".jpg", ".jpeg")
    needs_resize = size_of(path) > MAX_PX or os.path.getsize(path) > 1_200_000
    if not needs_convert and not needs_resize:
        return path
    if have_sips():
        cmd = ["sips", "-s", "format", "jpeg", "-s", "formatOptions", "80", "-Z", str(MAX_PX), path, "--out", target]
        subprocess.run(cmd, check=True, capture_output=True)
    else:
        from PIL import Image, ImageOps
        with Image.open(path) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            im.thumbnail((MAX_PX, MAX_PX))
            im.save(target, quality=80, optimize=True, progressive=True)
    if target != path:
        os.remove(path)
    return target


def main():
    os.makedirs(PHOTOS, exist_ok=True)
    ids = course_ids()
    manifest, unknown, changed = {}, [], 0
    for folder in sorted(os.listdir(PHOTOS)):
        fpath = os.path.join(PHOTOS, folder)
        if not os.path.isdir(fpath) or folder.startswith((".", "_")):
            continue
        if ids and folder not in ids:
            unknown.append(folder)
        files = []
        for name in sorted(os.listdir(fpath)):
            p = os.path.join(fpath, name)
            if not name.lower().endswith(IMG_EXT) or name.startswith("."):
                continue
            before = os.path.getsize(p)
            final = to_web_jpg(p)
            if final != p or os.path.getsize(final) != before:
                changed += 1
            files.append("photos/" + folder + "/" + os.path.basename(final))
        if files:
            manifest[folder] = files
    with open(os.path.join(ROOT, "photos.js"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by update_photos.py — don't edit by hand; add files to photos/<course-id>/ and re-run.\n\n")
        f.write("const PHOTOS = " + json.dumps(manifest, indent=1) + ";\n")
    total = sum(len(v) for v in manifest.values())
    print(f"photos.js updated: {total} photos across {len(manifest)} courses ({changed} resized/converted).")
    if unknown:
        print("\nThese folders don't match any course id in ledger-data.js (check the spelling in the Ledger tab):")
        for u in unknown:
            print("  photos/" + u)


if __name__ == "__main__":
    main()
